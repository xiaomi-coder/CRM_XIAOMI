const P2 = `The public library is such a familiar institution that its strangeness is easily overlooked. It
is a building, usually paid for from taxation, where anyone may enter without payment, take away objects of
value and return them later, and where staff are employed to help visitors find information without
enquiring why they want it. Almost nothing else in modern civic life operates on these terms.

Libraries themselves are ancient. Assyrian kings assembled clay tablets at Nineveh in the seventh century
BCE, and the library at Alexandria was famous throughout the classical world. These were not public in the
modern sense. Access was restricted to scholars, priests or the household of a ruler, and the collections
served the prestige of their owners as much as the pursuit of knowledge. Monastic libraries in medieval
Europe were similarly closed, and books, being manuscripts, were valuable enough to be chained to the
shelves.

The idea that a collection should be open to anyone emerged slowly and for practical reasons. Printing made
books cheaper, literacy spread, and by the eighteenth century commercial subscription libraries had appeared
in British and American towns, where members paid an annual fee for borrowing rights. These were popular but
exclusive by design: the subscription was set high enough to keep out those who could not afford it, which
was most of the population.

The decisive change came in the middle of the nineteenth century, and the arguments made at the time are
revealing. When the British Parliament debated the Public Libraries Act of 1850, supporters did not
primarily invoke the pleasures of reading. They argued that libraries would reduce drunkenness by offering
an alternative to the public house, that they would make workers more productive, and that an educated
population was less likely to riot. Opponents objected that taxation should not fund the leisure of others
and, more candidly, that education might make the labouring classes discontented with their position. The
Act passed narrowly and permitted local authorities to levy a halfpenny rate, an amount so small that many
early libraries could afford the building but not the books.

Philanthropy filled the gap, most famously through Andrew Carnegie, who funded more than two and a half
thousand library buildings between 1883 and 1929. His terms were deliberate: he paid for the structure only
if the local authority provided the site and committed to an annual maintenance budget of ten per cent of
the grant. The condition was intended to ensure that communities had a stake in the institution, and it
transformed the library from a gift into a public obligation.

The twentieth century broadened both collections and purpose. Fiction, initially regarded with suspicion by
librarians who feared novels would displace improving literature, came to dominate borrowing figures.
Children's sections, reference departments, newspapers, then records and films were added. The library
became, in the language of later policy documents, a community space rather than merely a collection.

That evolution has continued, and it explains why predictions of the library's obsolescence have repeatedly
proved wrong. When the internet made information abundant, the expected consequence was that libraries would
empty. In many countries visits did fall, but the services that grew were those that could not be obtained
online: internet access for households without it, help with government forms that exist only in digital
versions, warm spaces in winter, language classes, and supervised places for children after school. Studies
in several countries have found that the heaviest users are now disproportionately those with the lowest
incomes, precisely the group least able to substitute a private alternative.

This creates a difficulty for the way libraries are assessed. Funding decisions still tend to rely on the
number of books borrowed, a measure that captures less and less of what the institution actually does. A
library that lends fewer novels but helps a hundred people apply for benefits may appear, on the standard
metric, to be failing. Several national bodies are now attempting to measure social value instead,
though what to count, and how, remains unresolved.`;

const P3 = `Writing was invented independently at most four times in human history: in Mesopotamia around
3200 BCE, in China by 1200 BCE, in Mesoamerica by 300 BCE, and possibly in Egypt, where the evidence for
independence rather than borrowing is still debated. Every other script on earth, including this one,
descends from one of those beginnings. Given that spoken language is universal and probably older than our
species, the rarity of writing requires explanation.

Part of the answer is that writing was not invented to record language. The earliest Mesopotamian marks are
accounting notations: impressions on clay recording quantities of grain, oil and livestock. For roughly six
hundred years the system could represent numbers and commodities but not sentences. There was no way to write
"the barley belongs to the temple", only a symbol for barley beside a symbol for quantity, with ownership
implied by context. Writing began as bookkeeping, and it emerged in the first societies large enough that
transactions could no longer be remembered by the people involved.

The transition to full writing required a conceptual leap that is easy to underestimate: the realisation that
a symbol could represent a sound rather than a thing. The mechanism appears to have been something like a
rebus, in which a picture is used for its phonetic value regardless of meaning, as if a drawing of an eye
were used to write the word "I". Once that step was taken, anything sayable became writable, including names,
verbs and abstractions. Scripts that made this move survived; those that did not remained limited to
inventories.

The consequences of full writing were not straightforwardly beneficial, and contemporaries said so. Plato has
Socrates argue that writing would weaken memory, that a text cannot answer a question or defend itself, and
that readers would acquire the appearance of wisdom without its substance. The objection is more serious than
it first appears, and the irony that we know it only because Plato wrote it down has been observed many times.
Comparable anxieties accompanied printing, the newspaper and the internet, which suggests either that each
generation is unusually foolish or that something real is at stake each time a technology changes how
knowledge is stored.

Writing systems differ enormously in how much they demand of the learner. An alphabet with twenty-six
characters can be taught in a year; the Chinese system requires memorising several thousand characters over
a decade of schooling. It does not follow that alphabets are superior. Chinese characters are read directly
for meaning, which allows speakers of mutually unintelligible dialects to read the same text, and gives
modern readers access to documents two thousand years old. Any script represents a trade-off between the
effort of learning and the work the system can do.

The invention of writing also created a new form of inequality. In every early literate society, the ability
to read was restricted to a small class of scribes, priests and administrators, and that restriction was
often deliberate. Literacy conferred access to law, contracts, taxation records and sacred texts, and those
who controlled it controlled a great deal else. Mass literacy is a recent phenomenon: it was achieved in
northern Europe only in the nineteenth century, and globally the adult literacy rate passed fifty per cent
within living memory.

Modern communication has begun to blur the boundary that writing established. Text messages and social media
posts are written but often behave like speech: they are informal, immediate, unedited and increasingly
supplemented by images and emoji that function rather like the pictographic signs from which writing began.
Whether this represents decline or simply another adaptation is a question that could be asked of every
change writing has undergone in five thousand years, and it has usually been answered too quickly.`;

