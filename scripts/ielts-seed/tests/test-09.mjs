const P1 = `Standard economic models assume that people choose what is best for them given the information
available. The assumption was never intended as a description of psychology; it was a simplification that
made mathematics possible. The difficulty is that the errors people make are not random, which is what a
simplification would require. They are systematic, predictable and, in many cases, reversible by changing
how a choice is presented.

The foundational demonstration involved framing. Presented with a public health programme, respondents were
told that of six hundred people at risk, one option would save two hundred lives, while another carried a
one-third probability of saving all six hundred and a two-thirds probability of saving none. A large
majority chose the certain option. A second group received an arithmetically identical description phrased
in terms of deaths: four hundred people will die, versus a one-third chance that nobody dies. A large
majority now chose the gamble. The preference reversed on wording alone, and it did so among trained
physicians as reliably as among students.

The explanation offered is that people evaluate outcomes as gains or losses relative to a reference point
rather than in terms of final states, and that losses are felt roughly twice as strongly as equivalent
gains. This asymmetry, known as loss aversion, has consequences that are visible in markets. Investors hold
falling stocks too long, because selling converts a paper loss into a realised one. Consumers respond more
to a surcharge than to a discount of the same size, which is why firms present the cash price as standard
and the card price as a fee. Sellers demand more to give up an object than they would have paid to acquire
it, an effect demonstrated repeatedly with objects as trivial as a coffee mug.

A second family of findings concerns defaults. Whatever happens if a person does nothing is chosen far more
often than the alternative, and the effect is large enough to overwhelm strong stated preferences. Rates of
consent for organ donation differ by fifty percentage points or more between European countries whose
populations hold similar views, and the variable that predicts the difference is whether the form requires
opting in or opting out. Automatic enrolment in workplace pension schemes has raised participation
dramatically wherever it has been introduced. The explanations are several: inertia, the effort of
deciding, and the reasonable inference that the default was chosen by someone who knew what they were
doing.

These findings gave rise to what is usually called nudging: designing the environment in which choices are
made so that people are more likely to select what they themselves say they want, without removing any
options. Governments established behavioural units, and early results were striking, particularly in tax
compliance, where letters stating that most people in the recipient's area had already paid produced
measurable increases in payment at almost no cost.

The reaction has been more sceptical. Several celebrated effects have failed to replicate at scale, and the
published literature was found to contain a systematic bias towards positive results. Effect sizes that
appeared large in laboratory settings frequently shrink when applied to whole populations. There is also a
substantive objection: nudging addresses the symptoms of poor outcomes while leaving the structures that
produce them untouched. Reminding people to save is cheaper than raising wages, and its popularity with
governments may reflect that fact rather than its effectiveness.

The most durable contribution is probably not any particular intervention but the change in what economists
consider worth measuring. Once it is accepted that presentation affects choice, the design of a form, a
contract or a price display becomes an economic variable rather than an administrative detail. That
insight has been absorbed most enthusiastically not by policymakers but by commercial firms, which use the
same findings to increase spending rather than saving — a use of the research that its originators
anticipated and were unable to prevent.`;

const P2 = `In 1976 an economics professor in Bangladesh lent the equivalent of twenty-seven dollars, from his
own pocket, to a group of forty-two villagers who made bamboo furniture. They were trapped by the terms on
which they bought materials from traders, which left them almost nothing. All repaid. The experiment became
Grameen Bank, and the model it established — small loans, no collateral, borrowers organised into groups
that guaranteed one another — spread to more than a hundred countries and was awarded the Nobel Peace
Prize in 2006.

The reasoning was persuasive. The poor were assumed to be excluded from credit because they had nothing to
pledge and because the administrative cost of a small loan exceeded any interest it could earn.
Consequently they borrowed from moneylenders at rates that could exceed a hundred per cent a year. If that
constraint could be removed, it was argued, the poor would invest in small enterprises, incomes would rise
and repayment would follow. Group lending replaced collateral with social pressure, and weekly repayment
meetings kept default visible. Repayment rates above ninety-five per cent were reported consistently, far
higher than commercial banks achieve from wealthier customers.

For nearly three decades the evidence for the wider claims was largely anecdotal. From around 2005,
researchers began conducting randomised evaluations, in which access to microcredit was extended to
randomly selected neighbourhoods and outcomes compared with similar areas that had not yet received it. Six
such studies, conducted independently across four continents, produced a strikingly consistent picture,
and it was not what had been expected.

Access to microcredit did increase business activity. Households borrowed, some started or expanded small
enterprises, and investment in business assets rose. But there was no measurable average effect on
household income, on consumption, on health, on children's schooling or on measures of women's empowerment,
the outcomes on which the case for microfinance had largely rested. The gains were real but small, and
concentrated among borrowers who already had a business.

Two explanations are usually offered. The first is that most microenterprises are not scalable: a fourth
vegetable stall in a village competes with the existing three rather than creating new demand, so the
income gained by one household is partly lost by its neighbours. The second is that borrowers often did not
use loans for business at all. Substantial proportions went on medical costs, school fees, funerals and
smoothing consumption between harvests. This was treated initially as misuse, but it points to something
important: what many poor households lacked was not investment capital but a way to manage irregular
income and absorb shocks.

That reinterpretation has redirected the field. Attention has moved towards savings, insurance and payment
systems. Randomised studies of secure savings accounts have found effects on business investment and
consumption that microcredit did not produce, which is intuitive once it is recognised that a household
with no safe place to keep money is under continuous pressure to spend it. Mobile money has had larger
measurable effects than credit ever did: research on Kenya's M-Pesa estimated that access lifted a
substantial number of households out of extreme poverty, principally by making it cheap and quick to
receive help from relatives at the moment it was needed.

Microcredit itself has not disappeared and should not. It provides a service that is genuinely better than
the moneylender, and being able to borrow at a reasonable rate is valuable whether or not it transforms
incomes. What has ended is the claim that it constitutes a solution to poverty. The episode is now cited as
a case study in evaluation: a plausible idea, implemented widely and enthusiastically for thirty years
before anyone tested whether it did what was claimed, and found on testing to do something real but much
smaller.`;

const P3 = `A

Advertising is unusual among industries in that its central claim about itself is difficult to
verify. Firms spend around six hundred billion dollars a year globally, and the most quoted remark in the
business — that half of it is wasted, but nobody knows which half — was made over a century ago and remains
uncomfortably close to accurate.

B

The measurement problem is one of attribution. A company advertises and sales rise; the difficulty is
establishing that the second was caused by the first. Advertising expenditure is usually increased when
sales are expected to be strong, which builds a correlation into the data before any causal effect
operates. Digital advertising was expected to solve this, since clicks and purchases can be tracked
individually. In practice it introduced a subtler version of the same error. Advertising platforms optimise
delivery towards people most likely to buy, which means the audience shown an advertisement is
systematically composed of those who would have been most likely to purchase anyway. Controlled experiments
in which advertising is randomly withheld from some users have repeatedly found returns far below those
reported by the platforms' own attribution models, in several published cases by an order of magnitude.

C

What advertising demonstrably does is less concerned with information than the industry's older
self-description suggested. Very little advertising conveys facts about a product. Its more reliable
functions appear to be maintaining awareness, which decays if spending stops, and signalling. The signalling
argument holds that the expense itself is the message: a firm that spends heavily is credibly indicating
that it expects to remain in business and to attract repeat custom, which a firm selling a poor product
could not afford to do. This explains an otherwise puzzling feature of brand campaigns, which frequently say
almost nothing about the product while making it obvious that a great deal of money was spent.

D

Regulation has focused on falsehood, which is the least common problem. Explicitly false claims are
straightforward to prohibit and are prohibited nearly everywhere. Most contested advertising is literally
true and misleading in implication, and the boundary is difficult to draw in law. Restrictions on
advertising to children are the clearest area of agreement, on the reasoning that children below a certain
age do not reliably recognise persuasive intent, and several countries have banned it outright during
children's programming.

E

The economics have been transformed by the shift to digital. Two companies now receive roughly half of
global digital advertising revenue, and because they also control the systems that measure effectiveness,
they mark their own examination. The mechanism is an auction conducted in the milliseconds while a page
loads, in which advertisers bid for the attention of a specific individual on the basis of accumulated
behavioural data. This has funded services used by billions of people at no monetary cost, and it has
simultaneously produced a business model whose revenue depends on time spent and engagement, which are not
the same thing as user benefit and sometimes oppose it.

F

The consequences for the industries that advertising formerly supported have been severe. Newspaper
advertising revenue in most wealthy countries has fallen by seventy per cent or more since 2005, because
classified listings and local display advertising moved to platforms that could target more precisely. The
journalism that this revenue had cross-subsidised was not itself unprofitable in the sense of lacking
readers; it was funded by a mechanism that had no necessary connection to it and which technology removed.
Subscription models have partly replaced it in national outlets with distinctive content, and have largely
failed at local level, which is where the reduction in reporting has been most complete and where the
absence is hardest to notice.`;

