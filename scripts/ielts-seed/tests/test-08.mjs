const P1 = `In 1950, around twenty-five million international tourist journeys were made worldwide. By 2019
the figure had passed one and a half billion. Nothing comparable has happened to any other form of human
movement, and the consequences for the places at the receiving end have been correspondingly large.

The economic case for tourism is straightforward and often decisive. It earns foreign currency, it is
labour-intensive at a time when many industries are not, and it provides employment for people without
formal qualifications, including in rural regions with few alternatives. For a number of small island
states, tourism accounts for over a third of national income. Governments have therefore promoted it
vigorously, and the infrastructure built to serve visitors — airports, roads, water supply — is frequently
used by residents as well.

The difficulty is that the benefits and costs fall on different people. Studies of tourist spending
repeatedly find substantial leakage: in many developing destinations, between forty and eighty per cent of
the price paid by a visitor leaves the country almost immediately, to foreign-owned airlines, hotel chains
and tour operators. The jobs that remain locally are disproportionately seasonal, low-paid and insecure,
while the costs of congestion, water consumption and rising property prices are borne by residents
throughout the year. In Barcelona and Venice, the effect on housing has been particularly visible, as
apartments have shifted to short-term rental and long-standing residents have left. Venice has lost more
than half its resident population since 1970.

The term overtourism entered general use around 2017, and the protests that produced it were not directed
against visitors as individuals but against volume. The complaints follow a consistent pattern: the
displacement of ordinary shops by souvenir outlets, the conversion of housing, the erosion of public space,
and the sense that a place has been reorganised around a version of itself designed for outsiders. Cruise
ships attract particular anger because they concentrate thousands of arrivals into a few hours while
passengers eat and sleep aboard, producing crowding without proportionate spending.

Responses have generally taken one of three forms. The first is pricing: entry charges for day visitors in
Venice, higher tourist taxes in Amsterdam, and permit systems for popular trails. These reduce numbers at
the margin and raise revenue, but they also make access dependent on wealth, which is uncomfortable for
sites of shared cultural importance. The second is capping: limits on cruise arrivals, on new hotel
licences, or on daily visitor numbers, as in Bhutan, which has long required a substantial daily fee from
foreign visitors. The third is dispersal, which attempts to redistribute visitors to less-known areas
through marketing and transport, an approach that is politically comfortable but which risks exporting the
problem rather than solving it.

Assessment is complicated by the fact that visiting places is not merely an economic transaction. Contact
between people from different societies has generally been considered valuable, exposure to a place tends
to increase support for protecting it, and the revenue from wildlife tourism has been decisive in
conserving species that would otherwise have been eliminated as competitors for land. Some destinations
that were once economically marginal now sustain themselves through visitors who come specifically because
the culture and landscape have been retained rather than replaced.

The unavoidable problem is aviation. A single long-haul return flight can produce more carbon dioxide than
an average person in many countries emits in a year, and there is no near-term technological substitute for
the energy density of jet fuel over long distances. This creates an awkward asymmetry. The destinations
most dependent on tourism revenue are often those most exposed to the consequences of climate change, and
the visitors who reach them do so by a method that contributes to it. No policy currently in place resolves
that contradiction, and most proposals amount to reducing the number of people who fly, which returns the
question of who is permitted to travel and on what basis.`;

