const P1 = `For most of the twentieth century, parents in English-speaking countries were advised against
raising children with two languages. The prevailing view among educators was that a young mind had a fixed
capacity, that dividing it between two systems would leave both underdeveloped, and that bilingual children
would suffer confusion and delayed speech. Studies appeared to confirm this: bilingual children scored
lower on verbal tests than their monolingual peers.

The research was badly flawed. The bilingual children tested in the 1920s and 1930s were overwhelmingly the
children of recent immigrants, tested in their weaker language, often shortly after arriving in a new
country, and compared against middle-class native speakers. When the comparison was made properly, matching
children for socioeconomic background and testing in the stronger language, the deficit largely
disappeared. A study in Montreal in 1962 reversed the picture entirely, reporting that bilingual children
outperformed monolinguals on several measures. That paper is now regarded as the beginning of the modern
field, though it too has been criticised for selecting unusually able bilingual participants.

The picture that has emerged from more careful work is genuinely mixed, which is precisely why it is
interesting. Bilingual children do tend to have a smaller vocabulary in each individual language than
monolinguals have in their single language, although their combined vocabulary across both is equal or
larger. They are also slower, by a few hundredths of a second, at retrieving individual words, a phenomenon
familiar to any bilingual adult who has hesitated mid-sentence. These are real effects and they persist
into adulthood.

Against this, bilinguals appear to develop certain other abilities earlier. Because both languages remain
active in the mind whenever either is used, a bilingual speaker must continually suppress the one not
currently required. This constant management is thought to exercise a set of general-purpose mental
processes known as executive function, which govern attention, the ability to ignore irrelevant
information, and the flexibility to switch between tasks. Bilingual children have been shown to outperform
monolinguals on tasks where a rule changes partway through, or where a printed word conflicts with the
colour it is printed in.

The strength of this advantage has been the subject of a vigorous and instructive argument. Several
attempted replications in the 2010s failed to find the effect, and analysis of the published literature
revealed that studies reporting an advantage were substantially more likely to be published than those
finding nothing. The current consensus is more modest than the claims made a decade ago: the advantage is
real but small, appears most reliably in demanding conditions, and depends heavily on how frequently a
speaker actually switches between languages rather than on bilingualism as a category.

More robust is the evidence concerning ageing. Several independent studies of patients with dementia have
found that lifelong bilinguals show symptoms roughly four to five years later than monolinguals with
comparable education and occupation. Brain imaging suggests that this is not because bilingualism prevents
the underlying disease; the physical damage is often more advanced in bilingual patients at the point of
diagnosis. The explanation offered is cognitive reserve, the idea that a brain accustomed to managing
complexity can compensate for damage for longer before function visibly declines.

The practical consequences depend on how a second language is acquired. Immersion, where a child learns
subjects through the second language rather than studying the language itself, consistently produces better
results than conventional lessons, and does so without harming achievement in the first language. Age
matters less than is popularly believed for vocabulary and grammar, which adults can learn efficiently, but
a great deal for pronunciation, where the ability to acquire native-like accent declines steadily from
childhood. What predicts success most strongly at any age is not talent but the quantity of meaningful
interaction in the language, a finding that is consistent across every study but that curricula built
around grammatical exercises continue to ignore.`;

const P2 = `In 2010, a group of researchers examined how children in a Chinese city spent their afternoons
and found that the average eight-year-old had less than half an hour of unstructured free time a day. The
figure was widely reported as evidence of an unusually pressured educational culture. Comparable surveys in
Britain and the United States have since produced similar findings, and the decline has been steady across
three generations: children today spend substantially less time playing without adult direction than their
parents did, and dramatically less than their grandparents.

The reasons are neither mysterious nor irrational. Parents cite traffic, unfamiliar neighbours and a
perception that public space is unsafe, though recorded rates of crime against children have fallen in most
of these countries over the same period. Competition for school places has extended the school day and
filled the remainder with tutoring and structured activities. And play itself has been redefined:
supervised sports and educational classes are counted as play by adults, but they differ from the older
kind in the respect that matters most to developmental psychologists, which is that an adult decides what
happens.

The argument that this loss is significant rests on evidence from several directions. Play in mammals is
biologically expensive. Young animals at play burn energy, sustain injuries and expose themselves to
predators, and behaviours with those costs are not usually preserved by evolution unless they serve some
function. In rats, individuals deprived of rough-and-tumble play with peers, but otherwise raised normally,
grow into adults that overreact to mild threats and behave inappropriately in social encounters. The
deficit is specific to peer play; contact with adults does not substitute for it.

The proposed explanation is that free play is where children practise handling situations without an
authority present. When a group of children invents a game, they must agree on rules, resolve
disagreements, and calibrate their behaviour so that others continue to want to play, since the ultimate
sanction of exclusion is always available. Failure is immediate, minor and instructive. In supervised
activities, by contrast, disputes are settled by the adult, and the child practises appealing to authority
rather than negotiating with equals.

Risk plays a related role. Children in unsupervised play consistently seek out experiences that frighten
them slightly: climbing higher than is comfortable, moving fast, playing near water or in the dark. A
Norwegian research group has argued that this is an evolved mechanism for managing fear, in which a child
exposes itself to a controlled dose of something alarming and learns that the fear is survivable. The
prediction that follows is counterintuitive: children prevented from such experiences should become more
anxious rather than less, and studies of playground redesign are consistent with it. When schools have
replaced flat rubber surfaces and low equipment with more challenging structures, injury rates have
generally not risen, while reported bullying has fallen and concentration in class has improved.

Several education systems have responded. Finland has long protected fifteen minutes of outdoor break for
every forty-five minutes of teaching, regardless of weather. New Zealand schools that abolished playground
rules as an experiment reported fewer injuries and less disruptive behaviour, a result that surprised the
researchers involved. In several countries, legislation has been introduced to protect the right of
children to move independently in their neighbourhoods.

The objection to all of this is worth stating clearly. The evidence linking play deprivation to anxiety is
largely correlational in humans, since one cannot randomly assign childhoods, and the same decades that saw
play decline also saw the arrival of social media, academic intensification and changes in family
structure. Disentangling these is genuinely difficult. What can be said is that the burden of proof has
shifted: the assumption that time spent playing is time wasted, which underpinned a century of curriculum
design, now looks much harder to defend than the alternative.`;

const P3 = `Examinations are so embedded in education that it takes an effort to notice how strange they
are. A student's competence, developed over years, is inferred from performance during a few hours, under
time pressure, without reference materials, in conditions that resemble almost nothing they will encounter
afterwards. Defending this arrangement requires an argument, and the arguments made for it have changed
considerably over time.

The written examination has a longer history than is usually assumed. Imperial China operated competitive
examinations for entry into the civil service from the seventh century, and the system, at its height,
involved candidates sitting for several days in individual cells. Its purpose was explicitly political: to
recruit administrators on the basis of demonstrated ability rather than birth, and thereby to limit the
power of aristocratic families. European observers, including Voltaire, admired the principle, and the
British civil service adopted competitive examination in the 1850s partly on the Chinese model.

Meritocratic selection remains the strongest argument for formal assessment. Where places at university or
in employment are scarce, some means of allocation is necessary, and the alternatives to examination are
generally worse: interviews are subject to well-documented bias, teacher assessment correlates with
students' social background more strongly than examination results do, and reputation of school is worst of
all. Examinations are crude, but their crudeness is impersonal, and for candidates from families without
connections this has historically been an advantage rather than a defect.

The criticisms are equally substantial. The most serious concerns what assessment does to teaching. Once
the results of a test are used to judge schools and teachers, the test ceases to measure what it was
designed to measure, because effort shifts towards the test itself. This is a specific instance of a
general principle sometimes stated as Goodhart's law: when a measure becomes a target, it stops being a
good measure. In practice this appears as narrowing of the curriculum towards examined subjects,
extensive practice on past papers, and the teaching of techniques for answering questions rather than
understanding of the material. Studies of high-stakes testing regimes repeatedly find rising scores
accompanied by no improvement, and occasionally a decline, on independent measures of the same knowledge.

Timed examinations also measure things they do not intend to. Performance is affected by anxiety, by
handwriting speed, by whether a candidate has eaten, and by whether the specific topics that appeared
happened to be among those revised. Test-taking is itself a skill, distributed unevenly and coachable at
considerable expense, which introduces exactly the social bias the system was designed to exclude.

Alternatives have been tried and each carries its own difficulty. Continuous assessment through coursework
reduces the influence of a single occasion and permits work that resembles real practice, but it is
vulnerable to unequal help at home and, more recently, to text generated by machines. Portfolios capture
development over time but are slow and expensive to mark reliably, and agreement between markers is
generally lower than for examinations. Adaptive computer testing adjusts difficulty to the candidate and
measures more precisely in less time, but functions only for material that can be tested by discrete
questions with definite answers.

The direction of reform in several systems has therefore been mixed methods: examinations retained for
their comparability, combined with practical or project components in subjects where they are meaningful,
and results reported as profiles rather than a single figure. This is more informative and more expensive,
and it complicates the selection decisions that assessment exists to serve, which is the point at which
educational reform usually stalls. The deeper difficulty is that examinations are asked to do two
incompatible jobs at once: to support learning, which requires frequent low-stakes feedback, and to rank
candidates, which requires rare high-stakes judgement. Systems that try to do both with the same instrument
tend to sacrifice the first.`;

